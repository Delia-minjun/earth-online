export function PoemLine() {
  // 每次挂载抽一条；用 replace 化的取法，避免 Math.random 抖动重复渲染
  const line = useMemo(() => POEMS[Math.floor(Math.random() * POEMS.length)]!, []);

  return (
    <p
      className="mt-1.5 px-1 text-[9.5px] leading-relaxed text-ink-3"
      title="随机诗句"
    >
      【{line}】
    </p>
  );
}
